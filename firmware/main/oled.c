/* SSD1306 / SH1106 128x64 OLED, bit-banged I2C (see oled.h). */
#include "oled.h"
#include <stdint.h>
#include <string.h>
#include "driver/gpio.h"
#include "esp_rom_sys.h"

static uint8_t addr;                                             /* 7-bit address; 0: no display */

/* ------------------------------------------------------------ I2C, open drain: level 1 releases the line to the pull-up */

#define I2C_HALF_US 2                                            /* about 200 kHz */

static inline void sda(int v) { gpio_set_level(OLED_SDA_GPIO, v); }
static inline void scl(int v) { gpio_set_level(OLED_SCL_GPIO, v); esp_rom_delay_us(I2C_HALF_US); }

static void i2c_start(void) { sda(1); scl(1); sda(0); esp_rom_delay_us(I2C_HALF_US); scl(0); }
static void i2c_stop(void) { sda(0); scl(1); sda(1); esp_rom_delay_us(I2C_HALF_US); }

void (*oled_byte_hook)(void);

static bool i2c_byte(uint8_t b) {                                /* true: ACK */
    for (int i = 7; i >= 0; --i) {
        sda((b >> i) & 1);
        scl(1);
        scl(0);
    }
    sda(1);
    scl(1);
    const bool ack = gpio_get_level(OLED_SDA_GPIO) == 0;
    scl(0);
    if (oled_byte_hook) oled_byte_hook();
    return ack;
}

static bool cmds(const uint8_t *c, size_t n) {
    i2c_start();
    bool ok = i2c_byte(addr << 1) && i2c_byte(0x00);             /* control byte: commands follow */
    for (size_t i = 0; ok && i < n; ++i) ok = i2c_byte(c[i]);
    i2c_stop();
    return ok;
}

